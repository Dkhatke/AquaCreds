"""`aqua-api seed-demo`: a clearly labelled, **synthetic** demo project for UI work and demos.

Everything this module writes is synthetic and says so: the organisation, user and project names
carry "(synthetic)", emails use the reserved `example.org` domain, the project description, MRV
report notes and tenure "documents" state that they are demo data, satellite rows use the provider
`synthetic-demo` (never presented as Sentinel-2 data), and the field photos are generated images
(coloured blocks + EXIF), never real photographs. Values come from `random.Random(seed)`, so a seed
always produces the same project. Carbon figures are still computed by the real engine from these
synthetic inputs (via the normal report pipeline), so they are traceable, but not real removals.

The seed drives the in-process HTTP API (same validation, audit log and state machine as real use)
plus the worker task cores (evidence checks, report build, anchoring, issuance, indexing), so it
needs the full dev environment (`uv run aqua-api seed-demo`, or the dev image), not the slim API
image. It is idempotent: a re-run finds the existing rows and only completes missing steps.

Refuses to run when `APP_ENV=production`; `--with-chain` refuses any chain id other than Anvil's
31337. Passwords: `DEMO_PASSWORD` if set (min 10 chars), else generated per new account and
printed once; re-runs leave existing passwords unchanged."""

