def _rng(key: str) -> random.Random:
    """Deterministic, non-cryptographic generator for synthetic values (never for secrets)."""
    return random.Random(key)  # noqa: S311


class DemoSeedError(RuntimeError):
    """The demo cannot be seeded (refused, or a step failed); the message says why."""


@dataclass
class DemoResult:
    seed: int
    org_id: str
    project_id: str
    logins: list[tuple[str, str, str]]  # (role, email, password or note)
    created: list[str] = field(default_factory=list)  # step names done in this run
    report_ids: dict[str, str] = field(default_factory=dict)
    chain: dict[str, Any] = field(default_factory=dict)


Enqueued = list[tuple[str, tuple[Any, ...], str]]


