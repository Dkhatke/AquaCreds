def demo_email(role: str, seed: int) -> str:
    return f"demo.{role}.s{seed}@{EMAIL_DOMAIN}"


def org_name(seed: int) -> str:
    return f"Demo Mangrove Collective (synthetic, seed {seed})"


def project_name(seed: int) -> str:
    return f"Demo Bhitarkanika Restoration (synthetic, seed {seed})"


def boundary_origin(seed: int) -> tuple[float, float]:
    """South-west corner, inside the Bhitarkanika mangrove area; seeds 0-7 never overlap."""
    return 86.80 + (seed % 8) * 0.025, 20.62 + (seed // 8 % 4) * 0.025


def boundary(seed: int) -> dict[str, Any]:
    lon, lat = boundary_origin(seed)
    d = SIDE_DEG
    ring = [[lon, lat], [lon + d, lat], [lon + d, lat + d], [lon, lat + d], [lon, lat]]
    return {"type": "Polygon", "coordinates": [[[round(x, 6), round(y, 6)] for x, y in ring]]}


def plots(seed: int) -> dict[str, tuple[str, float, float]]:
    """code → (stratum, lon, lat): three dense and two sparse plots inside the boundary."""
    rng = _rng(f"plots-{seed}")
    lon, lat = boundary_origin(seed)
    out = {}
    for code, stratum in PLOT_LAYOUT:
        out[code] = (
            stratum,
            round(lon + rng.uniform(0.003, SIDE_DEG - 0.003), 6),
            round(lat + rng.uniform(0.003, SIDE_DEG - 0.003), 6),
        )
    return out


def trees(seed: int, code: str, stratum: str, monitoring: bool) -> list[dict[str, Any]]:
    """Synthetic tree records; monitoring trees are the baseline trees after growth."""
    rng = _rng(f"trees-{seed}-{code}")
    count = 6 if stratum == "dense" else 4
    out = []
    for _ in range(count):
        species = rng.choice(SPECIES)
        dbh = rng.uniform(1.2, 2.8)
        height = rng.uniform(1.0, 2.0)
        growth = rng.uniform(2.0, 4.5 if stratum == "dense" else 3.0)
        alive = not monitoring or rng.random() > 0.1
        if monitoring:
            dbh, height = dbh + growth, height + growth * 0.6
        out.append(
            {
                "species": species,
                "dbh_cm": round(dbh, 1),
                "height_m": round(height, 1) if alive else None,
                "alive": alive,
            }
        )
    return out


def synthetic_pdf(title: str) -> bytes:
    """A minimal one-page PDF stating that it is not a real document."""
    text = f"SYNTHETIC DEMO DOCUMENT - {title} - not a real permit or agreement"
    stream = f"BT /F1 12 Tf 40 760 Td ({text}) Tj ET".encode()
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R "
        b"/Resources << /Font << /F1 5 0 R >> >> >>",
        b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out = io.BytesIO()
    out.write(b"%PDF-1.4\n")
    offsets = []
    for i, body in enumerate(objects, start=1):
        offsets.append(out.tell())
        out.write(f"{i} 0 obj\n".encode() + body + b"\nendobj\n")
    xref = out.tell()
    out.write(f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode())
    for off in offsets:
        out.write(f"{off:010d} 00000 n \n".encode())
    out.write(
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    )
    return out.getvalue()


def _dms(value: float) -> tuple[float, float, float]:
    value = abs(value)
    d = int(value)
    m = int((value - d) * 60)
    return float(d), float(m), round((value - d - m / 60) * 3600, 4)


def synthetic_photo(seed: int, label: str, lon: float, lat: float, when: datetime) -> bytes:
    """A generated JPEG (random coloured blocks + a 'SYNTHETIC DEMO' banner) with EXIF GPS/time.
    Never a photograph of a real place or person."""
    from PIL import ExifTags, Image, ImageDraw

    rng = _rng(f"photo-{seed}-{label}")
    img = Image.new("RGB", (256, 192))
    draw = ImageDraw.Draw(img)
    for x in range(0, 256, 32):
        for y in range(0, 192, 32):
            g = rng.randint(60, 200)
            draw.rectangle(
                (x, y, x + 31, y + 31), fill=(rng.randint(10, 90), g, rng.randint(20, 90))
            )
    draw.rectangle((0, 0, 255, 18), fill=(0, 0, 0))
    draw.text((4, 3), f"SYNTHETIC DEMO PHOTO {label}", fill=(255, 255, 0))
    exif = Image.Exif()
    exif[ExifTags.Base.Make] = "AquaCreds demo generator"
    exif[ExifTags.Base.Model] = "synthetic"
    exif[ExifTags.Base.ImageDescription] = DEMO_TAG
    local = when.astimezone(UTC) + timedelta(hours=5, minutes=30)
    sub = exif.get_ifd(ExifTags.IFD.Exif)
    sub[ExifTags.Base.DateTimeOriginal] = local.strftime("%Y:%m:%d %H:%M:%S")
    sub[ExifTags.Base.OffsetTimeOriginal] = "+05:30"
    gps = exif.get_ifd(ExifTags.IFD.GPSInfo)
    gps[ExifTags.GPS.GPSLatitudeRef] = "N"
    gps[ExifTags.GPS.GPSLatitude] = _dms(lat)
    gps[ExifTags.GPS.GPSLongitudeRef] = "E"
    gps[ExifTags.GPS.GPSLongitude] = _dms(lon)
    buf = io.BytesIO()
    img.save(buf, "JPEG", quality=88, exif=exif)
    return buf.getvalue()


def synthetic_scenes(seed: int, project_id: uuid.UUID) -> list[SceneObservation]:
    """Monthly dry-season rows over both periods, provider `synthetic-demo`, item ids prefixed
    `SYNTHETIC-DEMO-`: chart fodder for the UI, never presented as Sentinel-2 observations."""
    rng = _rng(f"scenes-{seed}")
    rows = []
    for year, month in SCENE_MONTHS:
        day = date(year, month, 10 + rng.randint(0, 10))
        ndvi = 0.32 + 0.05 * (year - 2025) + rng.uniform(-0.03, 0.03)
        clear = round(rng.uniform(0.55, 0.98), 3)
        pixels = 44_000
        stats = {
            "ndvi": {
                "mean": round(ndvi, 4),
                "p10": round(ndvi - 0.12, 4),
                "p50": round(ndvi, 4),
                "p90": round(ndvi + 0.1, 4),
                "valid_pixels": round(pixels * clear),
            }
        }
        rows.append(
            SceneObservation(
                project_id=project_id,
                item_id=f"SYNTHETIC-DEMO-{day:%Y%m%d}-s{seed}",
                acquired_at=datetime(day.year, day.month, day.day, 5, 0, tzinfo=UTC),
                acquired_on=day,
                cloud_cover=round(rng.uniform(0, 30), 1),
                clear_fraction=clear,
                clear_pixels=round(pixels * clear),
                polygon_pixels=pixels,
                index_stats=stats,
                provider=SYNTHETIC_PROVIDER,
                processing_baseline=None,
            )
        )
    return rows


