class _Api:
    def __init__(self, client: httpx.AsyncClient, token: str) -> None:
        self.client, self.headers = client, {"Authorization": f"Bearer {token}"}

    async def call(self, method: str, url: str, *ok: int, **kw: Any) -> Any:
        r = await self.client.request(method, url, headers=self.headers, **kw)
        if r.status_code not in (ok or (200,)):
            raise DemoSeedError(f"{method} {url} -> {r.status_code}: {r.text[:500]}")
        return r.json() if r.content else None


def refuse_unsafe(settings: Settings, *, with_chain: bool) -> None:
    if settings.app_env == "production":
        raise DemoSeedError("seed-demo refuses to run with APP_ENV=production")
    if with_chain and settings.chain_id != ANVIL_CHAIN_ID:
        raise DemoSeedError(
            f"--with-chain only runs against a local Anvil (chain id {ANVIL_CHAIN_ID}); "
            f"CHAIN_ID is {settings.chain_id}"
        )
    if settings.staff_mfa_required:
        raise DemoSeedError("seed-demo needs MFA_REQUIRED_FOR_STAFF off (the development default)")


async def seed_demo(
    settings: Settings,
    *,
    seed: int = 42,
    with_chain: bool = False,
    storage: ObjectStorage | None = None,
    password: str | None = None,
    mine: Callable[[int], Awaitable[None]] | None = None,
) -> DemoResult:
    """Seed (or complete) the demo for `seed`. See the module docstring."""
    refuse_unsafe(settings, with_chain=with_chain)
    password = password if password is not None else os.environ.get("DEMO_PASSWORD")
    if password is not None and len(password) < 10:
        raise DemoSeedError("DEMO_PASSWORD must be at least 10 characters")

    from aqua_api.main import create_app
    from aqua_api.ratelimit import MemoryRateLimitBackend

    try:  # the worker cores live in the dev environment only (not the slim API image)
        from aqua_worker.tasks.evidence import run_checks
        from aqua_worker.tasks.reports import build_report_core
    except ImportError as exc:  # pragma: no cover - depends on the installed image
        raise DemoSeedError(
            "seed-demo needs the worker packages: run it with `uv run aqua-api seed-demo` "
            "or in the dev image"
        ) from exc

    app = create_app(settings)
    app.state.rate_limiter.backend = MemoryRateLimitBackend()
    if storage is not None:
        app.state.storage = storage
    store: ObjectStorage = app.state.storage
    enqueued: Enqueued = []
    app.state.enqueue = lambda name, *args, queue="default": enqueued.append((name, args, queue))
    sessionmaker = app.state.sessionmaker
    created: list[str] = []
    try:
        users, logins = await _users(app, seed, password, created)
        transport = httpx.ASGITransport(app=app)
        async with httpx.AsyncClient(transport=transport, base_url="http://demo/api/v1") as client:
            api = {role: _Api(client, token) for role, token in users.items()}
            org_id = await _org(api, sessionmaker, seed, logins, created)
            project_id = await _project(api, sessionmaker, store, seed, org_id, created)
            await _scenes(sessionmaker, seed, project_id, created)
            reports: dict[str, str] = {}
            for kind, dates in (("baseline", BASELINE), ("monitoring", MONITORING)):
                reports[kind] = await _period(
                    api,
                    store,
                    sessionmaker,
                    enqueued,
                    seed,
                    project_id,
                    kind,
                    dates,
                    created,
                    run_checks=run_checks,
                    build_report_core=build_report_core,
                )
        result = DemoResult(seed, org_id, str(project_id), logins, created, reports)
        if with_chain:
            result.chain = await _chain(settings, sessionmaker, org_id, reports, mine, created)
        return result
    finally:
        await app.state.engine.dispose()


async def _users(
    app: Any, seed: int, password: str | None, created: list[str]
) -> tuple[dict[str, str], list[tuple[str, str, str]]]:
    from aqua_api.security import create_access_token, hash_password
    from aqua_core import audit

    tokens: dict[str, str] = {}
    logins: list[tuple[str, str, str]] = []
    async with app.state.sessionmaker() as session:
        for role, (name, platform_role) in ROLES.items():
            email = demo_email(role, seed)
            user = await session.scalar(select(User).where(User.email == email))
            if user is None:
                secret = password or secrets.token_urlsafe(12)
                user = User(
                    email=email,
                    full_name=name,
                    password_hash=hash_password(secret),
                    platform_role=platform_role,
                )
                session.add(user)
                await session.flush()
                await audit.record(
                    session,
                    actor_id=None,
                    action="demo.user_created",
                    entity_type="user",
                    entity_id=user.id,
                    data={"platform_role": platform_role.value, "demo_seed": seed},
                )
                created.append(f"user:{role}")
                logins.append((role, email, secret))
            else:
                logins.append((role, email, "(existing account; password unchanged)"))
            tokens[role] = create_access_token(user.id, app.state.settings)[0]
        await session.commit()
    return tokens, logins


async def _org(
    api: dict[str, _Api], sessionmaker: Any, seed: int, logins: Any, created: list[str]
) -> str:
    async with sessionmaker() as session:
        org = await session.scalar(select(Organization).where(Organization.name == org_name(seed)))
    if org is None:
        body = await api["admin"].call(
            "POST", "/orgs", 201, json={"name": org_name(seed), "org_type": "ngo"}
        )
        org_id = str(body["id"])
        created.append("org")
    else:
        org_id = str(org.id)
    members = await api["admin"].call("GET", f"/orgs/{org_id}/members")
    field_email = demo_email("field", seed)
    if all(m["email"] != field_email for m in members):
        await api["admin"].call(
            "POST",
            f"/orgs/{org_id}/members",
            201,
            json={"email": field_email, "role": "field_agent"},
        )
        created.append("membership:field")
    return org_id


async def _project(
    api: dict[str, _Api],
    sessionmaker: Any,
    store: ObjectStorage,
    seed: int,
    org_id: str,
    created: list[str],
) -> uuid.UUID:
    admin = api["admin"]
    async with sessionmaker() as session:
        found = await session.scalar(
            select(Project.id).where(
                Project.org_id == uuid.UUID(org_id), Project.name == project_name(seed)
            )
        )
    if found is None:
        body = await admin.call(
            "POST",
            "/projects",
            201,
            json={
                "org_id": org_id,
                "name": project_name(seed),
                "description": f"{DEMO_TAG}. Boundary, plots, photos and satellite rows are "
                "generated from seed "
                f"{seed}.",
                "state": "Odisha",
                "tenure_type": "forest_land",
                "boundary": boundary(seed),
                "start_date": START.isoformat(),
                "planned_mangrove_share_pct": 95,
                "soil_disturbance_pct": 3,
            },
        )
        project_id = uuid.UUID(body["id"])
        created.append("project")
    else:
        project_id = found
    project = await admin.call("GET", f"/projects/{project_id}")
    if project["status"] == "draft":
        present = {d["kind"] for d in project.get("documents", [])}
        for kind in TENURE_DOCS:
            if kind in present:
                continue
            filename = f"synthetic-demo-{kind}.pdf"
            ticket = await admin.call(
                "POST",
                f"/projects/{project_id}/documents/upload-url",
                json={"kind": kind, "filename": filename, "content_type": "application/pdf"},
            )
            data = synthetic_pdf(kind.replace("_", " "))
            store.put_bytes(ticket["object_key"], data, "application/pdf")
            await admin.call(
                "POST",
                f"/projects/{project_id}/documents",
                201,
                json={
                    "object_key": ticket["object_key"],
                    "kind": kind,
                    "filename": filename,
                    "sha256": hashlib.sha256(data).hexdigest(),
                },
            )
            created.append(f"document:{kind}")
        await admin.call("POST", f"/projects/{project_id}/submit")
        created.append("project.submitted")
    return project_id


async def _scenes(sessionmaker: Any, seed: int, project_id: uuid.UUID, created: list[str]) -> None:
    async with sessionmaker() as session:
        existing = set(
            await session.scalars(
                select(SceneObservation.item_id).where(SceneObservation.project_id == project_id)
            )
        )
        new = [s for s in synthetic_scenes(seed, project_id) if s.item_id not in existing]
        session.add_all(new)
        await session.commit()
    if new:
        created.append(f"scenes:{len(new)}")


async def _period(
    api: dict[str, _Api],
    store: ObjectStorage,
    sessionmaker: Any,
    enqueued: Enqueued,
    seed: int,
    project_id: uuid.UUID,
    kind: str,
    dates: tuple[date, date, date],
    created: list[str],
    *,
    run_checks: Any,
    build_report_core: Any,
) -> str:
    """Open (or find) the period, record plots/measurements/photos, build and approve the report.
    Returns the approved report id."""
    admin, agent, verifier = api["admin"], api["field"], api["verifier"]
    start, end, measured = dates
    periods = await admin.call("GET", f"/projects/{project_id}/periods")
    period = next((p for p in periods if p["kind"] == kind), None)
    if period is None:
        period = await admin.call(
            "POST",
            f"/projects/{project_id}/periods",
            201,
            json={"kind": kind, "start_date": start.isoformat(), "end_date": end.isoformat()},
        )
        created.append(f"period:{kind}")
    period_id = period["id"]

    if period["status"] in ("open", "changes_requested"):
        layout = plots(seed)
        have = {
            p["code"]: p["id"] for p in await admin.call("GET", f"/projects/{project_id}/plots")
        }
        for code, (stratum, lon, lat) in layout.items():
            if code not in have:
                body = await admin.call(
                    "POST",
                    f"/projects/{project_id}/plots",
                    201,
                    json={
                        "code": code,
                        "stratum": stratum,
                        "lon": lon,
                        "lat": lat,
                        "area_m2": 100,
                        "marker_id": f"DEMO-{code}",
                    },
                )
                have[code] = body["id"]
                created.append(f"plot:{code}")
            r = await agent.client.post(
                f"/periods/{period_id}/plots/{have[code]}/measurements",
                headers=agent.headers,
                json={
                    "measured_on": measured.isoformat(),
                    "trees": trees(seed, code, stratum, kind == "monitoring"),
                },
            )
            if r.status_code == 201:
                created.append(f"measurement:{kind}:{code}")
            elif r.status_code != 409:  # 409 = already measured in this period
                raise DemoSeedError(f"measurement {code}: {r.status_code} {r.text[:300]}")
        # Photos are "captured" now (capture nonces are short-lived), so only the monitoring
        # period, whose window contains the seeding date, gets photo evidence.
        if kind == "monitoring" and not await agent.call(
            "GET", f"/periods/{period_id}/submissions"
        ):
            for code, (_, lon, lat) in layout.items():
                await _photo(
                    agent, store, sessionmaker, run_checks, seed, period_id, kind, code, lon, lat
                )
            created.append(f"photos:{kind}:{len(layout)}")
        area = (await admin.call("GET", f"/projects/{project_id}"))["area_ha"]
        await admin.call(
            "POST",
            f"/periods/{period_id}/reports",
            202,
            json={
                "strata_area_ha": {k: round(area * v, 2) for k, v in STRATA_SHARE.items()},
                "notes": DEMO_TAG,
            },
        )
        name, (pid, actor_id, options), _ = enqueued[-1]
        if name != "aqua.reports.build_report":  # pragma: no cover - API contract
            raise DemoSeedError(f"unexpected task {name}")
        built = await build_report_core(
            sessionmaker, store, uuid.UUID(pid), uuid.UUID(actor_id), json.loads(options)
        )
        if built["status"] != "built":
            raise DemoSeedError(f"{kind} report build failed: {built.get('error')}")
        created.append(f"report:{kind}")

    reports = await admin.call("GET", f"/periods/{period_id}/reports")
    latest = max(reports, key=lambda r: r["version"])
    if latest["status"] == "under_review":
        await verifier.call(
            "POST",
            f"/reports/{latest['id']}/review",
            json={"decision": "approve", "comment": f"Demo approval ({DEMO_TAG})"},
        )
        created.append(f"approved:{kind}")
    elif latest["status"] != "approved":
        raise DemoSeedError(f"{kind} report is {latest['status']}; fix it in the UI and re-run")
    return str(latest["id"])


async def _photo(
    agent: _Api,
    store: ObjectStorage,
    sessionmaker: Any,
    run_checks: Any,
    seed: int,
    period_id: str,
    kind: str,
    code: str,
    lon: float,
    lat: float,
) -> None:
    nonce = (await agent.call("POST", f"/periods/{period_id}/nonces", 201))["nonce"]
    ticket = await agent.call(
        "POST", f"/periods/{period_id}/photos/upload-url", json={"content_type": "image/jpeg"}
    )
    now = datetime.now(UTC)
    photo = synthetic_photo(seed, f"{kind}-{code}", lon, lat, now)
    store.put_bytes(ticket["object_key"], photo, "image/jpeg")
    sub = await agent.call(
        "POST",
        f"/periods/{period_id}/submissions",
        202,
        json={
            "object_key": ticket["object_key"],
            "sha256": hashlib.sha256(photo).hexdigest(),
            "nonce": nonce,
            "kind": "plot_centre",
            "plot_code": code,
            "lon": lon,
            "lat": lat,
            "gps_accuracy_m": 5.0,
            "captured_at": now.isoformat(),
            "device_model": "synthetic demo generator",
            "app_version": "demo",
        },
    )
    await run_checks(sessionmaker, store, uuid.UUID(sub["id"]), 25 * 1024 * 1024)


async def _chain(
    settings: Settings,
    sessionmaker: Any,
    org_id: str,
    reports: dict[str, str],
    mine: Callable[[int], Awaitable[None]] | None,
    created: list[str],
) -> dict[str, Any]:
    """Anchor both approved reports and issue the monitoring report's lCCC (local Anvil only)."""
    from aqua_chain import actions
    from aqua_chain.runtime import build_relayer, indexer_config
    from aqua_worker.tasks.chain import index_events_core, issue_credits_core, send_core
    from aqua_worker.tasks.reports import anchor_report_core

    relayer = build_relayer(settings, sessionmaker)
    try:
        chain_id = int(await relayer.client.w3.eth.chain_id)
        if chain_id != ANVIL_CHAIN_ID:
            raise DemoSeedError(f"RPC chain id is {chain_id}; --with-chain only runs on Anvil")

        async def _mine(blocks: int) -> None:
            if mine is not None:
                await mine(blocks)
            else:
                await relayer.client.w3.provider.make_request("anvil_mine", [hex(blocks)])

        for kind in ("baseline", "monitoring"):
            for _ in range(20):
                state = await anchor_report_core(relayer, uuid.UUID(reports[kind]))
                if state["state"] == "anchored":
                    break
                await _mine(relayer.policy.confirmations)
            else:
                raise DemoSeedError(f"{kind} report not anchored after 20 rounds")
        async with sessionmaker() as session:
            report = await session.get(MRVReport, uuid.UUID(reports["monitoring"]))
            if report is None or report.chain_report_id is None:
                raise DemoSeedError("the monitoring report was not anchored")
            existing = await actions.active_transaction(
                session, ChainTxPurpose.ISSUE_CREDITS, "mrv_report", str(report.id)
            )
            chain_report_id, lccc = report.chain_report_id, report.lccc_units
        if existing is None and lccc > 0:
            issued = await issue_credits_core(
                relayer,
                report_id=chain_report_id,
                credit_type="long_term",
                org_id=uuid.UUID(org_id),
                amount=lccc,
                expires_at=int(time.time()) + TEN_YEARS_S,
                entity_type="mrv_report",
                entity_id=reports["monitoring"],
            )
            tx_id = uuid.UUID(issued["id"])
            created.append("issue_credits")
        elif existing is not None:
            tx_id = existing.id
        else:
            raise DemoSeedError("the monitoring report has no lCCC to issue")
        for _ in range(10):
            issued = await send_core(relayer, tx_id)
            if issued["status"] == ChainTxStatus.CONFIRMED.value:
                break
            if issued["status"] in (ChainTxStatus.FAILED.value, ChainTxStatus.REVERTED.value):
                raise DemoSeedError(f"issuance {issued['status']}: {issued.get('error')}")
            await _mine(relayer.policy.confirmations)
        else:
            raise DemoSeedError("issuance not confirmed after 10 rounds")
        await _mine(settings.chain_reorg_depth + 1)
        await index_events_core(sessionmaker, relayer.client, indexer_config(settings))
        return {
            "chain_report_id": chain_report_id,
            "lccc_issued": lccc,
            "issue_tx_hash": issued["tx_hash"],
        }
    finally:
        await relayer.client.close()


def print_result(result: DemoResult, out: Callable[[str], None] = print) -> None:
    out(f"Demo seeded (seed {result.seed}); everything below is SYNTHETIC demo data.")
    out(f"  organisation: {org_name(result.seed)}  ({result.org_id})")
    out(f"  project:      {project_name(result.seed)}  ({result.project_id})")
    out(f"  created this run: {', '.join(result.created) or 'nothing (already complete)'}")
